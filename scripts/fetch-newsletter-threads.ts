interface CliArgs {
  senders: string[];
  sinceHours: number;
  bodyLimit: number;
  outPath: string;
  dryRun: boolean;
  discover: boolean;
  skipIdsFrom: string;
}

function parseArgs(argv: string[]): CliArgs {
  const args: CliArgs = {
    senders: [],
    sinceHours: 48,
    bodyLimit: DEFAULT_BODY_LIMIT,
    outPath: "",
    dryRun: false,
    discover: false,
    skipIdsFrom: "",
  };

  for (let i = 2; i < argv.length; i++) {
    switch (argv[i]) {
      case "--senders":
        args.senders = (argv[++i] ?? "")
          .split(",")
          .map((s) => s.trim())
          .filter(Boolean);
        break;
      case "--since-hours":
        args.sinceHours = parseInt(argv[++i] ?? "48", 10);
        break;
      case "--body-limit":
        args.bodyLimit = parseInt(argv[++i] ?? String(DEFAULT_BODY_LIMIT), 10);
        break;
      case "--out":
        args.outPath = argv[++i] ?? "";
        break;
      case "--discover":
        args.discover = true;
        break;
      case "--skip-ids-from":
        args.skipIdsFrom = argv[++i] ?? "";
        break;
      case "--dry-run":
        args.dryRun = true;
        break;
    }
  }

  return args;
}

/** Linha do manifesto append-only `{out}.fetch.jsonl` (#12188). */
export interface FetchManifestEvent {
  at: string;
  scope: string;
  query?: string;
  failed?: boolean;
  error?: string;
  thread_ids: string[];
  outcomes?: Array<{ thread_id: string; outcome: string; error?: string }>;
}

function appendManifest(absOut: string, event: Omit<FetchManifestEvent, "at">): void {
  mkdirSync(dirname(absOut), { recursive: true });
  appendFileSync(absOut + ".fetch.jsonl", JSON.stringify({ at: new Date().toISOString(), ...event }) + "\n");
}

function readJsonArray<T>(absPath: string): T[] {
  if (!existsSync(absPath)) return [];
  try {
    const parsed = JSON.parse(readFileSync(absPath, "utf8"));
    return Array.isArray(parsed) ? (parsed as T[]) : [];
  } catch {
    return []; /* corrupt file — overwrite */
  }
}

function writeJsonAtomic(absPath: string, value: unknown): void {
  mkdirSync(dirname(absPath), { recursive: true });
  const tmp = absPath + ".tmp";
  writeFileSync(tmp, JSON.stringify(value, null, 2) + "\n", "utf8");
  renameSync(tmp, absPath);
}

/**
 * #12188: modo descoberta. Grava num arquivo PRÓPRIO (nunca no
 * captured-newsletters.json) e nunca toca o sentinel de falha da captura —
 * quem decide se a captura falhou são os grupos de remetente.
 */
async function runDiscovery(args: CliArgs, request: typeof gmailRequest): Promise<void> {
  const scope = JSON.stringify({ discover: true, hours: args.sinceHours });
  const absOut = args.outPath ? resolve(process.cwd(), args.outPath) : "";
  const query = `in:inbox newer_than:${Math.ceil(args.sinceHours / 24)}d`;
  try {
    const skip = new Set(
      args.skipIdsFrom ? readJsonArray<{ thread_id?: string }>(resolve(process.cwd(), args.skipIdsFrom)).map((t) => t.thread_id) : [],
    );
    const found = await searchThreadIds(query, MAX_THREADS_PER_SEARCH, request, DISCOVERY_MAX_THREADS);
    const capped = found.length >= DISCOVERY_MAX_THREADS;
    if (capped) {
      console.error(`[fetch-newsletter-threads] WARN descoberta atingiu o teto de ${DISCOVERY_MAX_THREADS} threads — remetentes novos podem ter ficado de fora (#12188).`);
    }
    const discovered: DiscoveredThread[] = [];
    const outcomes: NonNullable<FetchManifestEvent["outcomes"]> = [];
    for (const id of found.filter((i) => !skip.has(i))) {
      try {
        const thread = await fetchThreadMetadata(id, request);
        if (!thread) continue; // sem List-ID/List-Unsubscribe: não é newsletter
        discovered.push(thread);
        outcomes.push({ thread_id: id, outcome: "descoberta" });
      } catch (err) {
        const msg = (err instanceof Error ? err.message : String(err)).slice(0, 200);
        console.error(`[fetch-newsletter-threads] WARN descoberta thread ${id}: ${msg}`);
        outcomes.push({ thread_id: id, outcome: "falhou", error: msg });
      }
    }
    const summary: FetchSummary = { threads_found: found.length, threads_written: discovered.length, skipped_no_body: 0, ...(capped ? { capped: true } : {}) };
    if (!args.dryRun && absOut) {
      appendManifest(absOut, { scope, query, thread_ids: outcomes.map((o) => o.thread_id), outcomes });
      const merged = new Map(readJsonArray<DiscoveredThread>(absOut).map((t) => [t.thread_id, t]));
      for (const t of discovered) merged.set(t.thread_id, t);
      writeJsonAtomic(absOut, [...merged.values()]);
    }
    console.log(JSON.stringify(summary, null, 2));
  } catch (err) {
    if (absOut && !args.dryRun) appendManifest(absOut, { scope, query, failed: true, error: String(err).slice(0, 200), thread_ids: [] });
    throw err;
  }
}

export async function main(argv: string[] = process.argv, request: typeof gmailRequest = gmailRequest): Promise<void> {
  const args = parseArgs(argv);

  if (args.senders.length === 0 && !args.discover) {
    console.error("--senders is required (comma-separated email addresses)");
    process.exit(1);
  }
  if (!args.outPath && !args.dryRun) {
    console.error("--out is required (unless --dry-run)");
    process.exit(1);
  }
  if (args.discover) return runDiscovery(args, request);

  // #2878: everything from here on can fail on OAuth/network (searchThreadIds
  // is the first Gmail REST call — `invalid_client` surfaces here). A fatal
  // error must leave a trace (sentinel) before rethrowing, so downstream
  // (inject-inbox-urls.ts → sync-coverage-line.ts / Stage 4 gate) can tell
  // "0b-bis falhou" apart from "editor genuinely sent 0 newsletters" instead
  // of silently asserting "0 submissões" (caso real: 260703, invalid_client).
  const scope = JSON.stringify({ senders: [...args.senders].map((s) => s.toLowerCase()).sort(), hours: args.sinceHours });
  let query = "";
  try {
    // Build Gmail search query: "from:(sender1 OR sender2) newer_than:Nd"
    const senderClause =
      args.senders.length === 1
        ? `from:${args.senders[0]}`
        : `from:(${args.senders.join(" OR ")})`;

    // Gmail accepts newer_than:Nd (days) — convert hours to days, ceiling
    const days = Math.ceil(args.sinceHours / 24);
    query = `${senderClause} newer_than:${days}d`;

    const threadIds = await searchThreadIds(query, MAX_THREADS_PER_SEARCH, request);
    if (threadIds.length === 0) {
      const summary: FetchSummary = { threads_found: 0, threads_written: 0, skipped_no_body: 0 };
      // No threads found: write an empty array ONLY if no prior output exists, so a
      // re-run with a narrower window doesn't wipe a previous run's captures.
      if (!args.dryRun && args.outPath) {
        const absOut = resolve(process.cwd(), args.outPath);
        appendManifest(absOut, { scope, query, thread_ids: [], outcomes: [] });
        if (!existsSync(absOut)) writeJsonAtomic(absOut, []);
      }
      // #2878: search succeeded (0 real). Clear any stale failure sentinel from a
      // prior failed run so a recovered re-run stops signalling capture_failed.
      if (!args.dryRun && args.outPath) clearCaptureFailedSentinel(args.outPath);
      console.log(JSON.stringify(summary, null, 2));
      return;
    }

    // Fetch sequentially to keep Gmail request concurrency bounded.
    // #12188: a thread that fails (no payload / request error) is recorded in
    // the manifest outcomes, NEVER as a placeholder in captured-newsletters.json
    // — `sender: ""` would count as a distinct newsletter in the coverage line.
    const captured: CapturedThread[] = [];
    const outcomes: NonNullable<FetchManifestEvent["outcomes"]> = [];
    let skippedNoBody = 0;

    for (const id of threadIds) {
      try {
        const thread = await fetchThread(id, args.bodyLimit, request);
        if (thread) {
          if (thread.capture_error) skippedNoBody++;
          captured.push(thread);
          outcomes.push({ thread_id: id, outcome: thread.capture_error ? "falhou" : "capturada", ...(thread.capture_error ? { error: thread.capture_error } : {}) });
        } else {
          skippedNoBody++;
          outcomes.push({ thread_id: id, outcome: "falhou", error: "Thread sem mensagem/payload" });
        }
      } catch (err) {
        // Non-fatal: log and continue
        const msg = (err instanceof Error ? err.message : String(err)).slice(0, 200);
        console.error(`[fetch-newsletter-threads] WARN thread ${id}: ${msg}`);
        skippedNoBody++;
        outcomes.push({ thread_id: id, outcome: "falhou", error: msg });
      }
    }

    const summary: FetchSummary = {
      threads_found: threadIds.length,
      threads_written: captured.length,
      skipped_no_body: skippedNoBody,
    };

    if (args.dryRun) {
      console.log("[dry-run] Would write:");
      if (captured.length > 0) {
        const first = captured[0];
        console.log(`  thread_id: ${first.thread_id}`);
        console.log(`  sender: ${first.sender}`);
        console.log(`  subject: ${first.subject}`);
        console.log(`  body (first 200 chars): ${first.body.slice(0, 200)}`);
      }
      console.log(JSON.stringify(summary, null, 2));
      return;
    }

    const absOut = resolve(process.cwd(), args.outPath);
    // Merge with existing output (crash-resume safety): a re-run that advances the
    // search window must not drop threads captured in a prior partial run.
    const existing = readJsonArray<CapturedThread>(absOut);
    appendManifest(absOut, { scope, query, thread_ids: outcomes.map((o) => o.thread_id), outcomes });
    writeJsonAtomic(absOut, mergeCaptured(existing, captured));

    // #2878: capture succeeded — clear any stale failure sentinel from a prior
    // failed run (recovery scenario), else downstream keeps signalling failure.
    clearCaptureFailedSentinel(args.outPath);
    console.log(JSON.stringify(summary, null, 2));
  } catch (err) {
    // #2878: fatal (OAuth/network) — write the failure sentinel BEFORE
    // rethrowing so the caller (main().catch below) still exits 1 as before,
    // but downstream steps can now see WHY threads_found is unknown/0.
    if (args.outPath && !args.dryRun) {
      appendManifest(resolve(process.cwd(), args.outPath), { scope, query, failed: true, error: String(err).slice(0, 200), thread_ids: [] });
      writeCaptureFailedSentinel(args.outPath, err);
    }
    throw err;
  }
}

