export interface CapturedThread {
  thread_id: string;
  sender: string;
  subject: string;
  date: string; // ISO date string
  body: string; // plain text, truncated to BODY_LIMIT
  urls_extraidas?: string[]; // preservados do corpo completo (#8668)
  /** #12188: a mensagem traz List-ID ou List-Unsubscribe. */
  newsletter_headers?: boolean;
  /** #12188: thread com metadados mas sem conteúdo aproveitável (motivo legível). */
  capture_error?: string;
}

/** #12188: thread achada pela descoberta — só metadados, nunca corpo. */
export interface DiscoveredThread {
  thread_id: string;
  sender: string;
  subject: string;
  date: string;
  list_id?: string;
  list_unsubscribe?: string;
  return_path?: string;
}

export interface FetchSummary {
  threads_found: number;
  threads_written: number;
  skipped_no_body: number;
  /** #12188 (só --discover): a busca bateu DISCOVERY_MAX_THREADS. */
  capped?: boolean;
}

// ---------------------------------------------------------------------------
// Gmail REST helpers
// ---------------------------------------------------------------------------

async function gmailRequest<T>(path: string): Promise<T> {
  const res = await gFetch(`${GMAIL_API}/${path}`);
  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Gmail API error (${res.status}) at /${path}: ${body.slice(0, 200)}`);
  }
  return res.json() as Promise<T>;
}

interface GmailThreadListResponse {
  threads?: Array<{ id: string; snippet?: string }>;
  resultSizeEstimate?: number;
  nextPageToken?: string;
}

/**
 * Search Gmail threads matching a query, exhausting pages of `maxResults` IDs.
 * `maxTotal` (#12188, descoberta) corta em N IDs — o chamador detecta o teto
 * por `ids.length >= maxTotal` e avisa.
 */
export async function searchThreadIds(
  query: string,
  maxResults = 20,
  request: typeof gmailRequest = gmailRequest,
  maxTotal = Number.POSITIVE_INFINITY,
): Promise<string[]> {
  const params = new URLSearchParams({ q: query, maxResults: String(maxResults) });
  const ids = new Set<string>();
  const pages = new Set<string>();
  while (true) {
    const data = await request<GmailThreadListResponse>(`threads?${params}`);
    for (const thread of data.threads ?? []) ids.add(thread.id);
    if (ids.size >= maxTotal) return [...ids].slice(0, maxTotal);
    if (!data.nextPageToken) return [...ids];
    if (pages.has(data.nextPageToken)) throw new Error("Gmail repetiu pageToken");
    pages.add(data.nextPageToken);
    params.set("pageToken", data.nextPageToken);
  }
}

// ---------------------------------------------------------------------------
// Body extraction — text/plain preferred, HTML stripped as fallback
// ---------------------------------------------------------------------------

function decodeBase64Url(str: string): string {
  const b64 = str.replace(/-/g, "+").replace(/_/g, "/");
  return Buffer.from(b64, "base64").toString("utf8");
}

/**
 * Recursively walk MIME parts, preferring text/plain. Returns empty string if
 * no readable body found.
 */
export function extractTextPart(part: GmailMessagePart): string {
  if (part.mimeType === "text/plain" && part.body?.data) {
    return decodeBase64Url(part.body.data);
  }
  if (part.parts) {
    for (const child of part.parts) {
      const text = extractTextPart(child);
      if (text) return text;
    }
  }
  return "";
}

/**
 * Fallback: extract HTML part when no text/plain found, strip tags.
 */
function extractHtmlPart(part: GmailMessagePart): string {
  if (part.mimeType === "text/html" && part.body?.data) {
    return stripHtmlForBody(decodeBase64Url(part.body.data));
  }
  if (part.parts) {
    for (const child of part.parts) {
      const text = extractHtmlPart(child);
      if (text) return text;
    }
  }
  return "";
}

/**
 * #10440: hrefs das partes text/html. Newsletters como AlphaSignal trazem
 * text/plain só com texto (links como "[1]" ou ausentes) e os links do artigo
 * só existem como <a href> no HTML — que o caminho text/plain nunca lia.
 */
export function extractHtmlHrefs(part: GmailMessagePart): string[] {
  const out: string[] = [];
  if (part.mimeType === "text/html" && part.body?.data) {
    const html = decodeBase64Url(part.body.data);
    for (const m of html.matchAll(/<a\b[^>]*?\shref\s*=\s*(?:"([^"]*)"|'([^']*)')/gi)) {
      const href = (m[1] ?? m[2] ?? "").replace(/&amp;/g, "&").trim();
      if (/^https?:\/\//i.test(href)) out.push(href);
    }
  }
  for (const child of part.parts ?? []) out.push(...extractHtmlHrefs(child));
  return out;
}

function getHeader(
  headers: Array<{ name: string; value: string }>,
  name: string,
): string {
  return (
    headers.find((h) => h.name.toLowerCase() === name.toLowerCase())?.value ?? ""
  );
}

/**
 * Merge freshly-fetched threads with any already on disk, deduplicated by
 * `thread_id`. Existing entries win (they may be from a wider prior window),
 * EXCEPT when the existing entry carries `capture_error` (#12188): a fresh
 * fetch of the same thread replaces it, so a retry recovers the body.
 *
 * Crash-resume safety: a partial Stage 0 re-run advances the search window;
 * threads captured in a prior run that fall outside the new window must not be
 * lost. Mirrors the merge pattern in capture-newsletter-urls.ts.
 */
export function mergeCaptured(
  existing: CapturedThread[],
  fresh: CapturedThread[],
): CapturedThread[] {
  const merged = new Map(existing.map((t) => [t.thread_id, t]));
  for (const t of fresh) {
    if (!merged.has(t.thread_id) || merged.get(t.thread_id)?.capture_error) merged.set(t.thread_id, t);
  }
  return [...merged.values()];
}

// ---------------------------------------------------------------------------
// Fetch single thread and convert to CapturedThread
// ---------------------------------------------------------------------------

interface GmailThreadFull {
  id: string;
  messages: Array<{
    id: string;
    internalDate: string;
    // payload may be absent on drafts / partial messages — guarded at call site.
    payload?: {
      mimeType: string;
      headers?: Array<{ name: string; value: string }>;
      body?: { data?: string };
      parts?: GmailMessagePart[];
    };
  }>;
}

/**
 * Fetch a single thread from Gmail REST API with full MIME structure,
 * extract text/plain body (or stripped HTML fallback), and return a compact
 * CapturedThread. Truncates body to `bodyLimit` chars.
 *
 * Why `format=full` (not `format=metadata`): we need the body to extract URLs.
 * But we truncate the extracted text immediately — the raw HTML never leaves
 * this function.
 */
export async function fetchThread(
  threadId: string,
  bodyLimit: number = DEFAULT_BODY_LIMIT,
  request: typeof gmailRequest = gmailRequest,
): Promise<CapturedThread | null> {
  const thread = await request<GmailThreadFull>(
    `threads/${threadId}?format=full`,
  );

  const messages = thread.messages ?? [];
  if (messages.length === 0) return null;

  // Pick the EARLIEST message: for a newsletter thread, the newsletter itself
  // is the first message. Later messages (replies, bounce-backs, auto-responders
  // grouped under the same threadId) would yield reply text instead of newsletter
  // content. Sort ascending by internalDate; empty/invalid dates sort first (treated
  // as earliest) so a missing date never promotes a reply over the newsletter.
  const sorted = [...messages].sort(
    (a, b) => (Number(a.internalDate) || 0) - (Number(b.internalDate) || 0),
  );
  const msg = sorted[0];

  // Guard payload itself: drafts/partial messages can arrive without a payload.
  if (!msg.payload) return null;

  const headers = msg.payload.headers ?? [];
  const sender = getHeader(headers, "From");
  const subject = getHeader(headers, "Subject");
  // Number("") === 0 (not NaN), so guard on the raw string too — an empty/absent
  // internalDate must not silently become 1970-01-01.
  const rawDate = (msg.internalDate ?? "").trim();
  const dateMs = Number(rawDate);
  const date =
    rawDate === "" || isNaN(dateMs)
      ? new Date().toISOString()
      : new Date(dateMs).toISOString();

  // Extract body: text/plain first, stripped HTML as fallback
  let body = extractTextPart(msg.payload as GmailMessagePart);
  if (!body) {
    body = extractHtmlPart(msg.payload as GmailMessagePart);
  }

  // #8668: extrair URLs do corpo COMPLETO antes do truncamento
  // #10440: une os hrefs do HTML (links que o text/plain não carrega).
  const urls_completo = [
    ...new Set([...extractUrls(body), ...extractHtmlHrefs(msg.payload as GmailMessagePart)]),
  ];

  // Truncate to limit — token-reduction core
  const truncated = body.length > bodyLimit ? body.slice(0, bodyLimit) : body;

  // #12188: preserve metadata even when the body cannot be read. An HTML that
  // is only images still counts as readable when it carries link hrefs.
  const unreadable = !truncated.trim() && urls_completo.length === 0;

  return {
    thread_id: thread.id,
    sender,
    subject,
    date,
    body: truncated,
    newsletter_headers: hasNewsletterHeaders(headers),
    ...(unreadable ? { capture_error: "Sem corpo legível" } : {}),
    urls_extraidas: urls_completo.length > 0 ? urls_completo : undefined,
  };
}

function hasNewsletterHeaders(headers: Array<{ name: string; value: string }>): boolean {
  return headers.some((h) => /^(list-id|list-unsubscribe)$/i.test(h.name));
}

const DISCOVERY_HEADERS = ["From", "Subject", "List-ID", "List-Unsubscribe", "Return-Path"];

/**
 * #12188: descoberta — lê só os metadados da 1ª mensagem (`format=metadata`).
 * Devolve null quando a thread não tem List-ID/List-Unsubscribe (não é
 * newsletter) ou não tem mensagem/payload.
 */
export async function fetchThreadMetadata(
  threadId: string,
  request: typeof gmailRequest = gmailRequest,
): Promise<DiscoveredThread | null> {
  const params = new URLSearchParams({ format: "metadata" });
  for (const h of DISCOVERY_HEADERS) params.append("metadataHeaders", h);
  const thread = await request<GmailThreadFull>(`threads/${threadId}?${params}`);
  const msg = [...(thread.messages ?? [])].sort(
    (a, b) => (Number(a.internalDate) || 0) - (Number(b.internalDate) || 0),
  )[0];
  if (!msg?.payload) return null;
  const headers = msg.payload.headers ?? [];
  if (!hasNewsletterHeaders(headers)) return null;
  const dateMs = Number((msg.internalDate ?? "").trim());
  const optional = (name: string) => getHeader(headers, name).slice(0, 300) || undefined;
  return {
    thread_id: thread.id,
    sender: getHeader(headers, "From"),
    subject: getHeader(headers, "Subject"),
    date: msg.internalDate && !isNaN(dateMs) ? new Date(dateMs).toISOString() : "",
    list_id: optional("List-ID"),
    list_unsubscribe: optional("List-Unsubscribe"),
    return_path: optional("Return-Path"),
  };
}

