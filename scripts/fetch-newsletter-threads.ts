/**
 * fetch-newsletter-threads.ts (#2452)
 *
 * Fetches newsletter threads from Gmail REST API and writes a compact
 * CapturedThread[] JSON — consuming only text/plain bodies (with HTML
 * stripped/truncated) so the orchestrator never loads full HTML emails
 * into its context window.
 *
 * Token-reduction rationale: the 0b-bis step in orchestrator-stage-0
 * previously called `mcp__claude_ai_Gmail__get_thread (FULL_CONTENT)` up to
 * ~20 times inline, loading 80–112k chars of HTML per newsletter email
 * directly into the parent context. This script offloads that I/O to a Bash
 * call — the orchestrator receives only a compact JSON summary.
 *
 * Usage:
 *   npx tsx scripts/fetch-newsletter-threads.ts \
 *     --senders "email1@example.com,email2@example.com" \
 *     --since-hours 48 \
 *     --out data/editions/{AAMMDD}/_internal/captured-newsletters.json
 *
 *   # #12188: descoberta de remetentes novos (só auditoria, nunca o pool)
 *   npx tsx scripts/fetch-newsletter-threads.ts --discover --since-hours 48 \
 *     --out data/editions/{AAMMDD}/_internal/discovered-newsletters.json \
 *     --skip-ids-from data/editions/{AAMMDD}/_internal/captured-newsletters.json
 *
 * Options:
 *   --senders    Comma-separated list of sender email addresses to search for.
 *   --since-hours  How far back to search (default: 48).
 *   --body-limit   Max chars to keep from each body (default: 8000).
 *   --out          Output file path. Ao lado dele vai o manifesto append-only
 *                  `{out}.fetch.jsonl` (um evento por execução, com escopo,
 *                  thread_ids e outcome de cada thread — inclusive as que falharam).
 *   --discover     Busca `in:inbox` na janela e grava em `--out` só os METADADOS
 *                  (`format=metadata`: From, Subject, List-ID, List-Unsubscribe,
 *                  Return-Path) das threads com List-ID/List-Unsubscribe. O corpo
 *                  nunca é lido: remetente novo não entra no pool até o editor
 *                  aprová-lo, e aí é buscado pelo modo `--senders`. NUNCA apontar
 *                  `--out` da descoberta para `captured-newsletters.json` (a linha
 *                  de cobertura conta os remetentes desse arquivo) e a descoberta
 *                  nunca grava nem limpa o sentinel `.capture-newsletter-failed.json`.
 *                  Teto de segurança DISCOVERY_MAX_THREADS, com aviso.
 *   --skip-ids-from  (com --discover) JSON CapturedThread[] cujos thread_id são pulados.
 *   --dry-run      Print thread count and first thread summary, no file write.
 *
 * Output file: CapturedThread[] (same shape as capture-newsletter-urls.ts expects)
 *   ou DiscoveredThread[] com --discover.
 * Stdout: JSON summary { threads_found, threads_written, skipped_no_body[, capped] }
 *
 * Requires data/.credentials.json (generated by scripts/oauth-setup.ts).
 */

